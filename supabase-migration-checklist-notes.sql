-- 開店前チェックに「手順メモ」を足す。
--
-- 経緯: 「トイレ清掃」の11項目は、「設備・清掃」の「トイレ・洗面所の清掃」と
-- 中身が重なっていて、30日でチェックされたのは3日(10%)だけだった。
-- 掃除そのものは97%やられているので、足りないのはチェック欄ではなく手順の掲示。
-- そこで、チェックの付かない「読むだけの項目」を持てるようにする。
--
-- is_note = true の項目は
--   ・チェック欄も数量欄も出ない(押す対象にならない)
--   ・「◯/◯ 完了」の分母にも、日報・アシスタントの集計にも入らない
-- ので、手順だけを画面に残せる。
--
-- 実行後、アプリの「編集」から11項目それぞれの「手順メモ」を押せば、
-- チェックは「トイレ・洗面所の清掃」の1個だけになり、中身は手順として残る。

alter table items add column if not exists is_note boolean not null default false;

-- 手順メモに切り替えた項目の、過去のチェック記録は意味がなくなるので消す。
-- (アプリ側でも切り替え時に当日ぶんを消しているが、ここは既存データの掃除)
delete from daily_records
where item_id in (select id from items where is_note);
